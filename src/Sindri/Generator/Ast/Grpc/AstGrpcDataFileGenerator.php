namespace Sindri\Generator\Ast\Grpc;

use Override;
use PhpParser\Node\Expr;
use PhpParser\Node\Scalar\String_;
use PhpParser\PrettyPrinter\Standard;
use PhpParser\PrettyPrinterAbstract;
use Sindri\Generator\Abstract\AstFileGenerator;
use Sindri\Generator\Enum\GenerateStatus;
use Sindri\Generator\Grpc\Contract\GrpcDataFileGeneratorContract;
use Valkyrja\Grpc\Routing\Data\Contract\RouteContract;
use Valkyrja\Grpc\Routing\Data\GrpcRoutingData;

/**
 * AST-based gRPC routing data file generator.
 *
 * Accepts PHP-Parser Expr nodes produced by GrpcRouteAttributeReader and pretty-prints them
 * directly into the generated data class, bypassing any runtime app boot.
 */
class AstGrpcDataFileGenerator extends AstFileGenerator implements GrpcDataFileGeneratorContract
{
    public function __construct(
        protected PrettyPrinterAbstract $printer = new Standard(),
    ) {
    }

    /**
     * @inheritDoc
     */
    #[Override]
    public function generateFile(
        string $directory,
        string $className,
        string $namespace,
        array $routes,
    ): GenerateStatus {
        return $this->writeFile($directory, $className, $this->generateFileContents($namespace, $className, $routes));
    }

    /**
     * @inheritDoc
     */
    #[Override]
    public function generateClassContents(array $routes): string
    {
        $dataNamespace = GrpcRoutingData::class;
        $routesContent = $this->getRoutesAsContent($routes);

        // phpcs:disable
        return <<<PHP
            new \\$dataNamespace(
                routes: $routesContent,
            )
            PHP;
        // phpcs:enable
    }

    /**
     * @param non-empty-string    $namespace
     * @param non-empty-string    $className
     * @param array<string, Expr> $routes
     *
     * @return non-empty-string
     */
    protected function generateFileContents(string $namespace, string $className, array $routes): string
    {
        $routingData   = GrpcRoutingData::class;
        $routesContent = $this->getRoutesAsContent($routes);

        return <<<PHP
            <?php

            declare(strict_types=1);

            // This file was automatically generated by Sindri.

            namespace $namespace;

            use $routingData;

            final readonly class $className extends GrpcRoutingData
            {
                public function __construct()
                {
                    parent::__construct(
                        routes: $routesContent,
                    );
                }
            }

            PHP;
    }

    /**
     * Pretty-print all routes into a PHP array literal string.
     *
     * @param array<string, Expr> $routes
     *
     * @return non-empty-string
     */
    protected function getRoutesAsContent(array $routes): string
    {
        $routeContract = RouteContract::class;
        $routesContent = '';

        foreach ($routes as $key => $routeExpr) {
            // A gRPC method key is always the literal `/package.Service/Method` string — unlike a
            // CLI route name, it is never a constant reference.
            $keyPhp         = $this->printer->prettyPrintExpr(new String_($key));
            $routePhp       = $this->printer->prettyPrintExpr($routeExpr);
            $routesContent .= <<<PHP
                $keyPhp => static fn (): \\$routeContract => $routePhp,

                PHP;
        }

        return <<<PHP
            [
                $routesContent
            ]
            PHP;
    }
}
